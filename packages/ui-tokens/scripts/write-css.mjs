// Writes dist/tokens.css from the built token objects so the web app can use CSS variables.
import { writeFileSync } from 'node:fs';
import { colors, toCssDeclarations } from '../dist/index.js';

const css = `/* Generated by packages/ui-tokens/scripts/write-css.mjs. Do not edit. */
:root {
${toCssDeclarations(colors.light)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${toCssDeclarations(colors.dark)}
  }
}

:root[data-theme='dark'] {
${toCssDeclarations(colors.dark)}
}
`;

writeFileSync(new URL('../dist/tokens.css', import.meta.url), css);
