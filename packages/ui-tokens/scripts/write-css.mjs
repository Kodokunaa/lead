// Writes dist/tokens.css from the built token objects so the web app can use CSS variables.
import { writeFileSync } from 'node:fs';
import { colors, fontFamily, motion, radius, shadow, toCssDeclarations } from '../dist/index.js';

const { emphasized, spring, ...durations } = motion;

const css = `/* Generated by packages/ui-tokens/scripts/write-css.mjs. Do not edit. */
:root {
  color-scheme: light;
${toCssDeclarations(colors)}
${toCssDeclarations(fontFamily, 'font')}
${toCssDeclarations(radius, 'radius', 'px')}
${toCssDeclarations(shadow, 'shadow')}
${toCssDeclarations(durations, 'duration', 'ms')}
${toCssDeclarations({ emphasized, spring }, 'ease')}
}
`;

writeFileSync(new URL('../dist/tokens.css', import.meta.url), css);
